#!/usr/bin/env bash
# ADR-0029 decision 7: prints which of the given migration SQL files are contract migrations, i.e.
# drop, rename, move or retype anything (`DROP`, `RENAME`, `SET SCHEMA`, `ALTER [COLUMN] <col>
# [SET DATA] TYPE`, the column plain or double-quoted, spaces included). Fails closed instead of
# parsing SQL: after drizzle-kit's own `--> statement-breakpoint` markers at the end of a line are
# removed, any other comment marker (`--`, `/*`, `*/`) counts as a contract, since a comment could
# split a keyword pair and stripping comments can't be done safely without a lexer (markers inside
# strings, quoted names or dollar-quoted bodies). Unicode-escaped names or strings (`U&"…"`,
# `U&'…'`) count too, since the column pattern can't read them. The keywords are matched anywhere
# in the text, strings included. Migrations are generated by drizzle-kit (Invariant 10), so a false
# positive is rare and costs a `!` in the PR title. Each file is read whole, so a statement may
# wrap across lines. A file that can't be read is an error (exit 2), never "no contract". Used by
# pr-title.yml (the PR title needs `!`), release.yml (contract precondition, breaking-release
# guard) and rollback.yml. Usage: scripts/contract-migrations.sh <file.sql>...
set -euo pipefail
ident='("([^"]|"")+"|[^[:space:]";]+)'
re='\bDROP\b|\bRENAME\b|\bSET[[:space:]]+SCHEMA\b|ALTER[[:space:]]+(COLUMN[[:space:]]+)?'"$ident"'[[:space:]]+(SET[[:space:]]+DATA[[:space:]]+)?TYPE\b|--|/\*|\*/|\bU&["'"'"']'
for f in "$@"; do
  [ -f "$f" ] || { echo "contract-migrations: $f is not a file" >&2; exit 2; }
  # A redirect, so an unreadable file fails here.
  sql="$(sed 's/--> statement-breakpoint$//' <"$f")" || { echo "contract-migrations: can't read $f" >&2; exit 2; }
  if grep -qziE -- "$re" <<<"$sql"; then printf '%s\n' "$f"; fi
done
