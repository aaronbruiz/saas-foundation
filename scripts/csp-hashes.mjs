// The CSP hashes for the two kinds of inline style the app's UI needs (ADR-0045, ADR-0046),
// computed from the installed packages:
// - style-src-elem: sonner's injected <style> (it appends an empty one, then its CSS);
// - style-src-attr: the `style` attributes Base UI's form controls render on the server (their
//   hidden inputs), collected by rendering each allowed control with react-dom/server.
// `pnpm csp:hashes` writes apps/app/src/server/csp-hashes.gen.ts; `--check` (in `pnpm check`) fails
// when the file differs from what the installed sonner, React and Base UI produce. A new hash is a
// CSP change: review it under ADR-0045 before regenerating.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'

process.env.NODE_ENV = 'production'
const root = new URL('..', import.meta.url).pathname
const out = `${root}apps/app/src/server/csp-hashes.gen.ts`
const req = createRequire(`${root}apps/app/package.json`)
const load = (id) => import(pathToFileURL(req.resolve(id)).href)
const hash = (s) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`

function sonnerHashes() {
  const file = req.resolve('sonner').replace(/index\.js$/, 'index.mjs')
  const calls = [...readFileSync(file, 'utf8').matchAll(/^__insertCSS\(("(?:[^"\\]|\\.)*")\)/gm)]
  if (calls.length !== 1)
    throw new Error(`sonner: expected one __insertCSS("…") call, found ${calls.length}`)
  return [hash(''), hash(JSON.parse(calls[0][1]))]
}

async function baseUiHashes() {
  const React = (await load('react')).default
  const { renderToString } = await load('react-dom/server')
  const h = React.createElement
  const m = (name) => load(`@base-ui/react/${name}`)
  const [
    { Select },
    { Checkbox },
    { Switch },
    { RadioGroup },
    { Radio },
    { NumberField },
    { Combobox },
  ] = await Promise.all(
    ['select', 'checkbox', 'switch', 'radio-group', 'radio', 'number-field', 'combobox'].map(m),
  )
  // Each allowed form control, with and without a `name` (the two hidden-input styles).
  const controls = [false, true].flatMap((named) => {
    const n = (v) => (named ? { name: v } : {})
    return [
      h(
        Select.Root,
        { ...n('s'), defaultValue: 'a', items: { a: 'A' } },
        h(Select.Trigger, null, h(Select.Value)),
      ),
      h(Checkbox.Root, n('c')),
      h(Switch.Root, n('w')),
      h(RadioGroup, { ...n('r'), defaultValue: 'x' }, h(Radio.Root, { value: 'x' })),
      h(NumberField.Root, { ...n('f'), defaultValue: 1 }, h(NumberField.Input)),
      h(Combobox.Root, { ...n('o'), items: ['a'] }, h(Combobox.Input)),
    ]
  })
  const decode = (s) =>
    s
      .replaceAll('&quot;', '"')
      .replaceAll('&#x27;', "'")
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&amp;', '&')
  const styles = new Set()
  for (const el of controls)
    for (const [, s] of renderToString(el).matchAll(/\sstyle="([^"]*)"/g)) styles.add(decode(s))
  return [...styles].sort().map(hash)
}

const render = (
  elem,
  attr,
) => `// Generated by scripts/csp-hashes.mjs (\`pnpm csp:hashes\`); \`pnpm check\` fails when it drifts.
// Don't edit: a changed hash is a CSP change (ADR-0045).

/** style-src-elem: sonner's injected <style>, empty and then with its CSS. */
export const STYLE_ELEM_HASHES = [
${elem.map((x) => `  "${x}",`).join('\n')}
] as const

/** style-src-attr: the \`style\` attributes Base UI's form controls render on the server. */
export const STYLE_ATTR_HASHES = [
${attr.map((x) => `  "${x}",`).join('\n')}
] as const
`

const elem = sonnerHashes()
const attr = await baseUiHashes()
if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8')
  const list = (name) =>
    [
      ...(current.match(new RegExp(`${name} = \\[([^\\]]*)\\]`))?.[1] ?? '').matchAll(
        /'sha256-[^']+'/g,
      ),
    ].map((x) => x[0])
  const same = (a, b) => a.length === b.length && a.every((x, i) => x === b[i])
  if (!same(list('STYLE_ELEM_HASHES'), elem) || !same(list('STYLE_ATTR_HASHES'), attr)) {
    console.error(
      `[csp-hashes] ${out} is stale: the installed sonner, React or Base UI produce\n  style-src-elem ${elem.join(' ')}\n  style-src-attr ${attr.join(' ')}\nA changed hash is a CSP change (ADR-0045): review it, then run \`pnpm csp:hashes\`.`,
    )
    process.exit(1)
  }
  console.log('[csp-hashes] up to date')
} else {
  writeFileSync(out, render(elem, attr))
  console.log(
    `[csp-hashes] wrote ${out}: ${elem.length} style-src-elem, ${attr.length} style-src-attr`,
  )
}
